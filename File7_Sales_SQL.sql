-- Top 10 Customer by Revenue

SELECT CUSTOMERNAME as Company_Name, CONTACTFIRSTNAME as First_Name, CONTACTLASTNAME as Last_Name, ROUND(SUM(QUANTITYORDERED * PRICEEACH), 2) as TotalRevenue, sum(QUANTITYORDERED) as Units_Sold, COUNT(ORDERNUMBER)
FROM sales_data_sample
WHERE status IN ("shipped")
GROUP BY CONTACTFIRSTNAME, CONTACTLASTNAME, CUSTOMERNAME
ORDER BY TotalRevenue DESC
LIMIT 10
;